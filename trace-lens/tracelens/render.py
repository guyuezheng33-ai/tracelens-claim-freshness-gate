"""Presentation layer: render graph query results into a viewable dashboard.

This is a real renderer, not a placeholder. Both exports are built from the
same in-memory query result and the same structured verdict, so the HTML
dashboard and the Markdown report can never disagree with each other.
"""
from __future__ import annotations

import html
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

from .querypacks import QUERIES

_STYLE = """
:root { color-scheme: light; }
body { font-family: system-ui, -apple-system, "Segoe UI", sans-serif;
       margin: 0; padding: 32px; background: #f7f8fa; color: #1d2330; }
h1 { font-size: 22px; font-weight: 600; margin: 0 0 4px; }
h2 { font-size: 16px; font-weight: 600; margin: 28px 0 10px; }
.sub { color: #5b6475; font-size: 13px; margin-bottom: 20px; }
.card { background: #fff; border: 1px solid #e2e6ee; border-radius: 10px;
        padding: 18px 20px; margin-bottom: 16px; }
.verdict { display: inline-block; font-size: 15px; font-weight: 600;
           padding: 4px 12px; border-radius: 6px; }
.pass { background: #e6f4ea; color: #17693a; }
.fail { background: #fce8e6; color: #a32d2d; }
table { border-collapse: collapse; width: 100%; font-size: 13px; }
th, td { text-align: left; padding: 7px 10px; border-bottom: 1px solid #edf0f5; }
th { color: #5b6475; font-weight: 600; }
.chain { display: inline-block; background: #eef3fb; border: 1px solid #cbdcf5;
         border-radius: 5px; padding: 2px 7px; font-family: ui-monospace, monospace;
         font-size: 12px; }
.arrow { color: #8a93a5; margin: 0 6px; }
.pathrow { margin: 8px 0; line-height: 2.2; }
code { background: #f1f3f7; border-radius: 4px; padding: 1px 5px; font-size: 12px; }
.muted { color: #5b6475; font-size: 12px; }
"""


def _esc(value: Any) -> str:
    return html.escape(str(value), quote=True)


def render_path_chain(path: Sequence[Any]) -> str:
    """Render one ordered node path as a chained HTML fragment."""
    nodes = [_esc(p) for p in path]
    return '<span class="chain">' + '</span><span class="arrow">&rarr;</span><span class="chain">'.join(nodes) + "</span>"


def render_checks_table(checks: Mapping[str, Any]) -> str:
    """Render the structured judge checks as a two-column HTML table."""
    rows = "".join(
        "<tr><td><code>%s</code></td><td>%s</td></tr>" % (_esc(k), "通过" if v else "未通过")
        for k, v in checks.items()
    )
    return "<table><thead><tr><th>检查项</th><th>结果</th></tr></thead><tbody>%s</tbody></table>" % rows


def render_dashboard_html(results: Mapping[str, list[dict[str, Any]]],
                          verdict: Mapping[str, Any], store: str) -> str:
    """Build the full self-contained HTML dashboard (no external assets)."""
    ok = verdict.get("verdict") == "PASS"
    badge = '<span class="verdict %s">%s</span>' % ("pass" if ok else "fail", _esc(verdict.get("verdict")))

    q1_paths = ""
    for row in results.get("Q1", []):
        score = _esc(row.get("score"))
        q1_paths += '<div class="pathrow">%s <span class="muted">&middot; %s 分 &middot; %s 跳</span></div>' % (
            render_path_chain(row.get("path", [])), score, _esc(row.get("hops", ""))
        )
    if not q1_paths:
        q1_paths = '<p class="muted">该答案无可达的低分来源路径（零误报）。</p>'

    pack_rows = "".join(
        "<tr><td>%s</td><td>%s</td><td>%s</td><td>%d</td></tr>" % (
            _esc(k), _esc(QUERIES.get(k, {}).get("name", "")),
            _esc(QUERIES.get(k, {}).get("question", "")), len(rows),
        )
        for k, rows in results.items()
    )

    baseline = _esc(verdict.get("baseline_global_lowest_score_picks"))
    causes = ", ".join(_esc(c) for c in verdict.get("convergence_causes", [])) or "—"

    return """<!doctype html>
<html lang="zh-CN"><head><meta charset="utf-8">
<title>TraceLens dashboard</title><style>%s</style></head><body>
<h1>TraceLens &middot; Agent trace 图诊断</h1>
<div class="sub">store: <code>%s</code> &middot; 报告由查询结果与结构判定同源生成</div>
<div class="card"><h2>结构判定</h2>%s<div class="sub">%s</div>%s</div>
<div class="card"><h2>分数基线 vs 图定位</h2>
<table><thead><tr><th>判定方式</th><th>选中来源</th></tr></thead><tbody>
<tr><td>全局最低分基线</td><td><code>%s</code>（误判）</td></tr>
<tr><td>Q2 收敛 motif 定义的真因</td><td><code>%s</code></td></tr>
</tbody></table></div>
<div class="card"><h2>Q1 证据路径</h2>%s</div>
<div class="card"><h2>四个查询包</h2>
<table><thead><tr><th>包</th><th>名称</th><th>回答的问题</th><th>行数</th></tr></thead><tbody>%s</tbody></table></div>
<p class="muted">Generated by tracelens.render &middot; 同源导出：docs/report.html / docs/report.md</p>
</body></html>
""" % (_STYLE, _esc(store), badge, _esc(verdict.get("metric", "")),
       render_checks_table(verdict.get("checks", {})), baseline, causes, q1_paths, pack_rows)


def render_report_markdown(results: Mapping[str, list[dict[str, Any]]],
                           verdict: Mapping[str, Any], store: str) -> str:
    """Build the Markdown report from exactly the same data as the HTML view."""
    lines = [
        "# TraceLens 诊断报告",
        "",
        "- store: `%s`" % store,
        "- 结构判定: **%s**" % verdict.get("verdict"),
        "- 指标: %s" % verdict.get("metric", ""),
        "",
        "## 判定检查",
        "",
        "| 检查项 | 结果 |",
        "| --- | --- |",
    ]
    lines += ["| `%s` | %s |" % (k, "通过" if v else "未通过")
              for k, v in verdict.get("checks", {}).items()]
    lines += [
        "",
        "## 分数基线 vs 图定位",
        "",
        "| 判定方式 | 选中来源 |",
        "| --- | --- |",
        "| 全局最低分基线 | `%s`（误判） |" % verdict.get("baseline_global_lowest_score_picks"),
        "| 收敛 motif 真因 | %s |" % (", ".join("`%s`" % c for c in verdict.get("convergence_causes", [])) or "—"),
        "",
        "## Q1 证据路径",
        "",
    ]
    q1 = results.get("Q1", [])
    if q1:
        for row in q1:
            lines.append("- `%s` · %s 分 · %s 跳" % (
                " -> ".join(str(p) for p in row.get("path", [])), row.get("score"), row.get("hops")
            ))
    else:
        lines.append("- 无可达低分来源路径（零误报）。")
    lines += ["", "## 四个查询包", "", "| 包 | 回答的问题 | 行数 |", "| --- | --- | --- |"]
    lines += ["| %s | %s | %d |" % (k, QUERIES.get(k, {}).get("question", ""), len(rows))
              for k, rows in results.items()]
    lines += ["", "---", "", "由 tracelens.render 生成；与 docs/report.html 同源。", ""]
    return "\n".join(lines)


def render_to_file(fmt: str, out: Path, results: Mapping[str, list[dict[str, Any]]],
                   verdict: Mapping[str, Any], store: str) -> Path:
    """Write either the HTML dashboard or the Markdown report to disk."""
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    if fmt == "html":
        text = render_dashboard_html(results, verdict, store)
    elif fmt == "md":
        text = render_report_markdown(results, verdict, store)
    else:
        raise ValueError("unsupported report format: %s" % fmt)
    out.write_text(text, encoding="utf-8")
    return out
